#!/data/data/com.termux/files/usr/bin/bash
# gen-docs-index.sh — generate the docs index table (and verify it in --check).
#
# Convention: a doc may declare metadata in its first 12 lines:
#   > 状态：active|snapshot|historical
#   > 适用版本：<range>        (optional; "-" when absent)
# The "last verified" date is taken from git (never hand-typed):
#   git log -1 --format=%as -- <file>
#
# Output: a markdown table grouped by directory, wrapped in
#   <!-- docs-index:begin --> … <!-- docs-index:end -->
# inside docs/README.md (replaced in place by default; --check compares only).
#
# Usage:
#   tools/gen-docs-index.sh            # rewrite the block in docs/README.md
#   tools/gen-docs-index.sh --check    # exit 1 when the block is stale
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
DOCS="$ROOT_DIR/docs"
README="$DOCS/README.md"
BEGIN="<!-- docs-index:begin -->"
END="<!-- docs-index:end -->"
MODE="${1:-write}"

[[ -d "$DOCS" ]] || { echo "Error: docs/ not found" >&2; exit 2; }
[[ -f "$README" ]] || { echo "Error: docs/README.md not found" >&2; exit 2; }

declare -a DIRS=("." "install" "build" "packaging" "runbooks" "reference" "history" "incidents" "measurements")

meta_of() { # meta_of <file> <key>
  sed -n '1,12s/.*'"$2"'：\([^|｜]*\).*/\1/p' "$1" | head -n1 | sed 's/[[:space:]]*$//'
}

title_of() { # title_of <file>
  local t
  t="$(grep -m1 '^# ' "$1" | sed 's/^# //')"
  [[ -n "$t" ]] || t="$(basename "$1")"
  printf '%s' "$t"
}

date_of() { # date_of <file>
  git -C "$ROOT_DIR" log -1 --format=%as -- "${1#"$ROOT_DIR"/}" 2>/dev/null || printf ''
}

generate() {
  echo "$BEGIN"
  echo "<!-- generated by tools/gen-docs-index.sh — do not edit by hand -->"
  for d in "${DIRS[@]}"; do
    local abs="$DOCS" dir_label files
    [[ "$d" == "." ]] && abs="$DOCS" || abs="$DOCS/$d"
    [[ -d "$abs" ]] || continue
    if [[ "$d" == "." ]]; then
      files="$(find "$abs" -maxdepth 1 -type f -name '*.md' ! -name 'README.md' ! -name 'AGENTS.md' | sort)"
      dir_label="."
    else
      files="$(find "$abs" -type f -name '*.md' | sort)"
      dir_label="$d"
    fi
    [[ -n "$files" ]] || continue
    printf '\n### `%s`\n\n| 文档 | 状态 | 适用版本 | 最后核实 |\n|---|---|---|---|\n' "$dir_label"
    while IFS= read -r f; do
      [[ -f "$f" ]] || continue
      local rel="${f#"$DOCS"/}"
      local status ver date
      status="$(meta_of "$f" '状态')"
      if [[ -z "$status" ]]; then
        case "$rel" in history/*) status="historical" ;; *) status="active" ;; esac
      fi
      ver="$(meta_of "$f" '适用版本')"; [[ -n "$ver" ]] || ver="—"
      date="$(date_of "$f")"; [[ -n "$date" ]] || date="—"
      printf '| [%s](%s) | %s | %s | %s |\n' "$(title_of "$f")" "$rel" "$status" "$ver" "$date"
    done <<<"$files"
  done
  echo
  echo "$END"
}

BLOCK="$(generate)"

if [[ "$MODE" == "--check" ]]; then
  if ! grep -qF "$BEGIN" "$README" || ! grep -qF "$END" "$README"; then
    echo "Error: docs-index markers missing in docs/README.md" >&2
    exit 1
  fi
  current="$(awk -v b="$BEGIN" -v e="$END" '$0==b{f=1} f{print} $0==e{f=0}' "$README")"
  if [[ "$current" != "$BLOCK" ]]; then
    echo "Error: docs index is stale — run tools/gen-docs-index.sh" >&2
    diff <(printf '%s\n' "$current") <(printf '%s\n' "$BLOCK") | head -20 >&2 || echo "(diff truncated)" >&2
    exit 1
  fi
  echo "docs index: up to date"
  exit 0
fi

BLOCK="$BLOCK" python3 - "$README" "$BEGIN" "$END" <<'PY'
import os, sys
readme, begin, end = sys.argv[1], sys.argv[2], sys.argv[3]
block = os.environ["BLOCK"]
src = open(readme, encoding="utf-8").read()
if begin not in src or end not in src:
    sys.exit("docs-index markers missing in docs/README.md")
head, rest = src.split(begin, 1)
_, tail = rest.split(end, 1)
open(readme, "w", encoding="utf-8").write(head + block.rstrip("\n") + tail)
print("docs index: written")
PY
